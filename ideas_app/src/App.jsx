// Простая обёртка над localStorage, чтобы имитировать window.storage.get/set
if (typeof window !== "undefined" && !window.storage) {
  window.storage = {
    async get(key) {
      try {
        const value = window.localStorage.getItem(key);
        return { value };
      } catch {
        return { value: null };
      }
    },
    async set(key, value) {
      try {
        window.localStorage.setItem(key, value);
      } catch {
        // ignore
      }
    },
  };
}

